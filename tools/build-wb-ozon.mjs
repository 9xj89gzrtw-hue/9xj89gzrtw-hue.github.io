#!/usr/bin/env node
/* Builds the WB & Ozon seller inspector userscript from its sources.
 *
 *   node tools/build-wb-ozon.mjs
 *
 * core.js (pure card + margin + CSV logic) and panel.js (the shadow-root UI)
 * are the only sources; the userscript is one header plus those two files,
 * so a fix never has to be made twice.
 */
import fs from "node:fs";
import path from "node:path";
import { execFileSync } from "node:child_process";

const ROOT = path.resolve(import.meta.dirname, "..");
const SRC = path.join(ROOT, "wb-ozon-seller-inspector");
const OUT = path.join(ROOT, "downloads");

const core = fs.readFileSync(path.join(SRC, "core.js"), "utf8");
const panel = fs.readFileSync(path.join(SRC, "panel.js"), "utf8");
const version = (/var VERSION = "([^"]+)"/.exec(core) || [])[1];
if (!version) throw new Error("core.js: no VERSION constant");

const HEADER = `// ==UserScript==
// @name         WB & Ozon Seller Inspector — margin + competitor export to Excel
// @name:ru      WB и Ozon: продавцы, чистая маржа и выгрузка конкурентов в Excel
// @namespace    https://9xj89gzrtw-hue.github.io/data-clipper/
// @version      ${version}
// @description  On wildberries.ru and ozon.ru the pill counts product cards, shows seller info, computes unit margin (commission, SPP, tax, logistics, cost) and exports them to Excel-friendly CSV in one click. Free tier stops at 50 cards; a TW1-CLIP key removes the limit offline.
// @description:ru На wildberries.ru и ozon.ru пилюля считает карточки товаров, показывает продавца, считает чистую маржу (комиссия, СПП, налог, логистика, закуп) и выгружает их в Excel-дружелюбный CSV одним кликом. Бесплатно до 50 карточек; ключ TW1-CLIP снимает лимит офлайн.
// @author       Toolworks
// @homepageURL  https://9xj89gzrtw-hue.github.io/userscripts/
// @supportURL   https://9xj89gzrtw-hue.github.io/data-clipper/
// @downloadURL  https://9xj89gzrtw-hue.github.io/downloads/wb-ozon-seller-inspector.user.js
// @updateURL    https://9xj89gzrtw-hue.github.io/downloads/wb-ozon-seller-inspector.user.js
// @match        https://www.wildberries.ru/*
// @match        https://wildberries.ru/*
// @match        https://www.ozon.ru/*
// @match        https://ozon.ru/*
// @run-at       document-idle
// @grant        none
// @noframes
// @license      MIT
// ==/UserScript==

/* Generated by tools/build-wb-ozon.mjs from wb-ozon-seller-inspector/core.js
 * and wb-ozon-seller-inspector/panel.js. Do not edit this file: edit the
 * sources. */
`;

const bundle = HEADER + "\n" + core + "\n" + panel + "\n";

fs.mkdirSync(OUT, { recursive: true });
fs.writeFileSync(path.join(OUT, "wb-ozon-seller-inspector.user.js"), bundle, "utf8");
console.log("userscript  " + path.join("downloads", "wb-ozon-seller-inspector.user.js") + "  " + (bundle.length / 1024).toFixed(1) + " KB");

/* SHA256SUMS.txt: same format as the shipped file, rewritten whole so no
   stale checksum survives. */
const sumsPath = path.join(OUT, "SHA256SUMS.txt");
const entries = fs.readdirSync(OUT)
  .filter((f) => f !== "SHA256SUMS.txt" && !f.endsWith(".sha256") && fs.statSync(path.join(OUT, f)).isFile())
  .sort();
let out = "";
for (const f of entries) {
  const h = execFileSync("shasum", ["-a", "256", path.join(OUT, f)]).toString().split(" ")[0];
  out += h + "  " + f + "\n";
}
fs.writeFileSync(sumsPath, out, "utf8");
console.log("sha256      " + path.join("downloads", "SHA256SUMS.txt") + "  (" + entries.length + " files)");
