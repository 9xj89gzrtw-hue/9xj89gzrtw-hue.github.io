#!/usr/bin/env node
/* Builds the one-file userscript and the extension zip from the shared core.
 *
 *   node tools/build-userscript.mjs
 *
 * core.js and panel.js are the only sources; the userscript is a header plus
 * those two files, so a fix never has to be made twice.
 */
import fs from "node:fs";
import path from "node:path";
import { execFileSync } from "node:child_process";

const ROOT = path.resolve(import.meta.dirname, "..");
const SRC = path.join(ROOT, "audio-dub-kombo");
const OUT = path.join(ROOT, "downloads");

const core = fs.readFileSync(path.join(SRC, "core.js"), "utf8");
const panel = fs.readFileSync(path.join(SRC, "panel.js"), "utf8");
const manifest = JSON.parse(fs.readFileSync(path.join(SRC, "manifest.json"), "utf8"));
const version = manifest.version;

const HEADER = `// ==UserScript==
// @name         YouTube & VK Audio + Yandex AI-Dub Downloader
// @name:ru      YouTube и VK: звук + озвучка Яндекса в 1 клик
// @namespace    https://9xj89gzrtw-hue.github.io/audio-dub-extractor/
// @version      ${version}
// @description  Three buttons under a video: download the Yandex AI-dub soundtrack, download the original audio (M4A/MP3), and mark a clip in/out that opens in Studio with BWF/ID3 timecode.
// @description:ru Три кнопки под видео: скачать озвучку нейроперевода Яндекса, скачать оригинальный звук (M4A/MP3) и отправить клип по таймкоду в Studio с BWF/ID3-метками.
// @author       Toolworks
// @homepageURL  https://9xj89gzrtw-hue.github.io/audio-dub-extractor/
// @supportURL   https://9xj89gzrtw-hue.github.io/audio-dub-extractor/#pricing
// @match        https://www.youtube.com/*
// @match        https://youtube.com/*
// @match        https://youtu.be/*
// @match        https://vk.com/*
// @match        https://vkvideo.ru/*
// @match        https://rutube.ru/*
// @run-at       document-start
// @grant        none
// @noframes
// @license      MIT
// ==/UserScript==

/* Generated by tools/build-userscript.mjs from audio-dub-kombo/core.js and
 * audio-dub-kombo/panel.js. Do not edit this file: edit the sources. */
`;

const banner = `/* Audio Dub Kombo ${version} — generated, see audio-dub-kombo/ */`;
const bundle = HEADER + "\n" + banner + "\n" + core + "\n" + panel + "\n";

fs.mkdirSync(OUT, { recursive: true });
fs.writeFileSync(path.join(OUT, "audio-dub-tools.user.js"), bundle, "utf8");
console.log("userscript  " + path.join("downloads", "audio-dub-tools.user.js") + "  " + (bundle.length / 1024).toFixed(1) + " KB");

/* Extension zip: same files, plus the manifest, the bridge and the worker. */
const zipPath = path.join(OUT, "audio-dub-kombo-ext.zip");
if (fs.existsSync(zipPath)) fs.unlinkSync(zipPath);
execFileSync(
  "zip",
  ["-r", "-X", "-q", zipPath, "audio-dub-kombo", "-x", "*.DS_Store", "-x", "__MACOSX/*"],
  { cwd: path.dirname(SRC) }
);
const stat = fs.statSync(zipPath);
console.log("extension   " + path.join("downloads", "audio-dub-kombo-ext.zip") + "  " + (stat.size / 1024).toFixed(1) + " KB");

/* A stale checksum file is worse than none, so it is rewritten every build. */
const sha = execFileSync("shasum", ["-a", "256", zipPath]).toString().split(" ")[0];
fs.writeFileSync(
  path.join(OUT, "audio-dub-kombo-ext.sha256"),
  sha + "  audio-dub-kombo-ext.zip\n",
  "utf8"
);
console.log("sha256      " + sha);
