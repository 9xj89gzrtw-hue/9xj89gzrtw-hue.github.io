#!/usr/bin/env node
/* Bundle table-tg-clipper/clipper.js into a Tampermonkey userscript.
 *
 *   node tools/build-clipper.mjs
 *
 * The @match is broad because the point is "any page with a table", but the
 * script itself stays invisible until it finds a real table or a t.me/s/ feed,
 * and one click dismisses it for good. That keeps it clear of "spam script"
 * complaints on sites where it has nothing to do.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const SRC = path.join(ROOT, "table-tg-clipper");
const OUT = path.join(ROOT, "downloads");

const manifest = JSON.parse(fs.readFileSync(path.join(SRC, "manifest.json"), "utf8"));
const body = fs.readFileSync(path.join(SRC, "clipper.js"), "utf8");
const version = manifest.version;

const header = `// ==UserScript==
// @name         ${manifest.name}
// @name:ru      ${manifest.name_ru}
// @namespace    https://9xj89gzrtw-hue.github.io/data-clipper/
// @version      ${version}
// @description  ${manifest.description}
// @description:ru ${manifest.description_ru}
// @author       Toolworks
// @homepageURL  https://9xj89gzrtw-hue.github.io/userscripts/
// @supportURL   https://9xj89gzrtw-hue.github.io/data-clipper/
// @downloadURL  https://9xj89gzrtw-hue.github.io/downloads/table-tg-clipper.user.js
// @updateURL    https://9xj89gzrtw-hue.github.io/downloads/table-tg-clipper.user.js
// @match        *://*/*
// @run-at       document-idle
// @grant        none
// @noframes
// @license      MIT
// ==/UserScript==

/* Generated by tools/build-clipper.mjs from table-tg-clipper/clipper.js.
 * Do not edit this file: edit the source and rebuild. */
`;

const bundle = header + "\n" + body;
fs.mkdirSync(OUT, { recursive: true });
const dest = path.join(OUT, "table-tg-clipper.user.js");
fs.writeFileSync(dest, bundle, "utf8");
console.log("userscript  " + path.relative(ROOT, dest) + "  " + (bundle.length / 1024).toFixed(1) + " KB  v" + version);
